<?php

class P11_AverageOfTwoNumbers {
    public function main(): void {
        // Define two numbers
        $numA = 20;
        $numB = 15;

        // Output the formula and result
        // Write the program here
        $result = $numA + $numB;
        $average = $result / 2;
        echo "The average is " . $average . "\n";
    }
}
